// Generates the flags block of README.md from templates/ (`npm run readme`).
// test/unit/readme.test.ts fails when README.md is out of sync.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadAxes, type AxisRegistry } from "../src/axes.ts";
import { loadLayers, type LayerSet } from "../src/layers.ts";
import { templatesRoot } from "../src/paths.ts";
import { PACKAGE_MANAGERS } from "../src/pm.ts";
import { disabledAxesFor } from "../src/resolve.ts";

export const START = "<!-- flags:start (generated by `npm run readme`; do not edit) -->";
export const END = "<!-- flags:end -->";
export const readmePath = fileURLToPath(new URL("../README.md", import.meta.url));

function flagOf(axes: AxisRegistry, axis: string): string {
  return axes.axes.get(axis)?.flag ?? `--${axis}`;
}

function describeLayer(id: string, axes: AxisRegistry): string {
  const [axis = "", option = ""] = id.split("/");
  return axes.axes.has(axis) ? `\`${flagOf(axes, axis)} ${option}\`` : `\`${id}\``;
}

/** "Not with `--type library`" notes per axis, derived from `disablesAxes`. */
function disabledNotes(layers: LayerSet, axes: AxisRegistry): Map<string, string[]> {
  const notes = new Map<string, string[]>();
  for (const axis of axes.promptOrder) {
    for (const option of axes.axes.get(axis)?.options ?? []) {
      for (const disabled of disabledAxesFor({ [axis]: option }, layers, axes)) {
        notes.set(disabled, [...(notes.get(disabled) ?? []), `\`${flagOf(axes, axis)} ${option}\``]);
      }
    }
  }
  return notes;
}

/** Unsupported pairs, from `requires` and `conflicts` (deduplicated, both directions). */
function unsupported(layers: LayerSet, axes: AxisRegistry): string[] {
  const lines = new Set<string>();
  for (const layer of layers.values()) {
    for (const [axis, allowed] of Object.entries(layer.manifest.requires ?? {})) {
      if (allowed === undefined) continue;
      lines.add(`${describeLayer(layer.id, axes)} requires ${allowed.map((o) => `\`${flagOf(axes, axis)} ${o}\``).join(" or ")}.`);
    }
    for (const other of layer.manifest.conflicts ?? []) {
      const [a, b] = [layer.id, other].sort();
      lines.add(`${describeLayer(a ?? "", axes)} can't be combined with ${describeLayer(b ?? "", axes)}.`);
    }
  }
  return [...lines].sort();
}

/** The generated Markdown between START and END. */
export function flagsBlock(root = templatesRoot()): string {
  const axes = loadAxes(root);
  const layers = loadLayers(root, axes);
  const notes = disabledNotes(layers, axes);
  const rows = ["| Flag | Options | Default |", "|---|---|---|"];
  for (const id of axes.promptOrder) {
    const axis = axes.axes.get(id);
    if (axis === undefined) continue;
    const options = axis.options
      .map((o) => {
        const m = layers.get(`${id}/${o}`)?.manifest;
        return `\`${o}\`${m?.hint === undefined ? "" : ` (${m.hint})`}`;
      })
      .join("<br>");
    const note = notes.get(id);
    const label = `\`${axis.flag} <option>\`<br>${axis.message}${note === undefined ? "" : `; not used with ${note.join(", ")}`}`;
    rows.push(`| ${label} | ${options} | \`${axis.default}\` |`);
  }
  rows.push(`| \`--pm <pm>\`, \`--package-manager <pm>\`<br>Package manager | ${PACKAGE_MANAGERS.map((p) => `\`${p}\``).join(", ")} | the one running \`npm create\`, else \`npm\` |`);
  rows.push("| `-y`, `--yes`<br>Use defaults for every choice not given by flag; never prompt | | |");
  rows.push("| `-v`, `--version` / `-h`, `--help` | | |");
  return [START, "", ...rows, "", "Unsupported combinations (the CLI exits with the flag that fixes it):", "", ...unsupported(layers, axes).map((l) => `- ${l}`), "", END].join("\n");
}

/** README text with the block replaced. Throws if the markers are missing. */
export function withFlagsBlock(readme: string, block = flagsBlock()): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error(`README.md needs the markers:\n${START}\n${END}`);
  return readme.slice(0, start) + block + readme.slice(end + END.length);
}

if (import.meta.main) {
  writeFileSync(readmePath, withFlagsBlock(readFileSync(readmePath, "utf8")));
  console.log(`updated ${readmePath}`);
}
